export type MessageKey = keyof typeof dictionary.th;

/** Looks up a key and fills {placeholders}; falls back to Thai, then to the key itself. */
export function translate(lang: Lang, key: MessageKey, vars?: Record<string, string | number>): string {
  const table = dictionary[lang] as Record<string, string>;
  const text = table[key] ?? (dictionary.th as Record<string, string>)[key] ?? key;
  return vars ? text.replace(/\{(\w+)\}/g, (match, name) => name in vars ? String(vars[name]) : match) : text;
}
