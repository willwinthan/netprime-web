/** Minimal RFC 4180 CSV parsing/writing (UTF-8, optional BOM, quoted fields, CRLF or LF). */

export function parseCsv(text: string): string[][] {
  const input = text.charCodeAt(0) === 0xfeff ? text.slice(1) : text;
  const rows: string[][] = [];
  let row: string[] = [];
  let field = "";
  let quoted = false;
  for (let i = 0; i < input.length; i++) {
    const ch = input[i];
    if (quoted) {
      if (ch === '"') {
        if (input[i + 1] === '"') { field += '"'; i++; } else quoted = false;
      } else field += ch;
    } else if (ch === '"' && field === "") {
      quoted = true;
    } else if (ch === ",") {
      row.push(field); field = "";
    } else if (ch === "\n" || ch === "\r") {
      if (ch === "\r" && input[i + 1] === "\n") i++;
      row.push(field); field = "";
      rows.push(row); row = [];
    } else field += ch;
  }
  if (field !== "" || row.length) { row.push(field); rows.push(row); }
  // Blank lines carry no data.
  return rows.filter(r => r.some(cell => cell.trim() !== ""));
}

/** Quotes when needed and defuses spreadsheet formulas (=, +, -, @ at the start). */
export function csvCell(value: unknown): string {
  let text = value === null || value === undefined ? "" : String(value);
  if (/^[=+\-@\t\r]/.test(text)) text = "'" + text;
  return /[",\r\n]/.test(text) ? `"${text.replace(/"/g, '""')}"` : text;
}

/** CSV with a UTF-8 BOM so Excel shows Thai correctly. */
export function toCsv(header: string[], rows: unknown[][]): string {
  return "\ufeff" + [header, ...rows].map(r => r.map(csvCell).join(",")).join("\r\n") + "\r\n";
}
